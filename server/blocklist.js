const IGNORED_CHARS = /[\s，。！？、；：,.!?;:'"“”‘’()（）[\]【】{}<>《》_\-~·|/\\*+#@&%^]/g;

function normalize(text) {
  return String(text ?? '').toLowerCase().replace(IGNORED_CHARS, '');
}

const NORMALIZED_WORDS = BANNED_WORDS.map((word) => ({
  raw: word,
  normalized: normalize(word),
})).filter((item) => item.normalized.length > 0);

/// 返回命中的屏蔽词，未命中返回 null
export function findBannedWord(...texts) {
  const content = normalize(texts.filter(Boolean).join('\n'));
  for (const item of NORMALIZED_WORDS) {
    if (content.includes(item.normalized)) return item.raw;
  }
  return null;
}
